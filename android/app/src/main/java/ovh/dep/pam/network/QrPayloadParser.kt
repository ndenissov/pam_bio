package ovh.dep.pam.network

import kotlinx.serialization.json.Json
import java.util.Base64

/**
 * Parses QR / base64 / JSON pairing payloads generated by `pambiod pair`.
 */
object QrPayloadParser {
    private val defaultJson = Json { ignoreUnknownKeys = true }

    fun parseBytes(bytes: ByteArray, json: Json = defaultJson): QrPairingPayload? {
        return try {
            if (bytes.isNotEmpty()) {
                val nameLen = bytes[0].toInt() and 0xFF
                if (nameLen in 1..bytes.size - 33) {
                    val serviceName = String(bytes, 1, nameLen, Charsets.UTF_8)
                    val pubKeyBytes = bytes.copyOfRange(1 + nameLen, 1 + nameLen + 32)
                    val pubKeyBase64 = Base64.getEncoder().encodeToString(pubKeyBytes)
                    if (serviceName.isNotBlank()) {
                        return QrPairingPayload(serviceName, pubKeyBase64)
                    }
                }
            }
            val str = String(bytes, Charsets.UTF_8).trim()
            val payload = json.decodeFromString<QrPairingPayload>(str)
            if (payload.serviceName.isNotBlank() && payload.pcPubKey.isNotBlank()) {
                payload
            } else {
                null
            }
        } catch (_: Exception) {
            null
        }
    }

    fun parseBase64Text(text: String, json: Json = defaultJson): QrPairingPayload? {
        return try {
            val cleaned = text.trim()
            val decoded = Base64.getMimeDecoder().decode(cleaned)
            parseBytes(decoded, json)
        } catch (_: Exception) {
            // Fallback: maybe user pasted raw JSON directly
            try {
                val payload = json.decodeFromString<QrPairingPayload>(text.trim())
                if (payload.serviceName.isNotBlank() && payload.pcPubKey.isNotBlank()) payload else null
            } catch (_: Exception) {
                null
            }
        }
    }
}

